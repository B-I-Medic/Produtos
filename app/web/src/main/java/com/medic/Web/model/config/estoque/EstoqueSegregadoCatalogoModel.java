package com.medic.Web.model.config.estoque;

import com.medic.Web.config.persistence.UUIDAutoGenerated;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.springframework.data.annotation.Id;
import org.springframework.data.relational.core.mapping.Column;
import org.springframework.data.relational.core.mapping.Table;

import java.io.Serial;
import java.io.Serializable;
import java.time.Instant;
import java.util.UUID;

@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
@Table("estoque_segregado_catalogo")
public class EstoqueSegregadoCatalogoModel implements Serializable, UUIDAutoGenerated {

    @Serial
    private static final long serialVersionUID = 1L;

    @Id
    private UUID id;

    @Column("id_empresa")
    private UUID idEmpresa;

    @Column("cod_segregado")
    private int codSegregado;

    @Column("descricao")
    private String descricao;

    @Column("cod_ibge")
    private String codIBGE;

    @Column("ativo")
    private boolean ativo;

    @Column("atualizado_por")
    private UUID atualizadoPor;

    @Column("atualizado_em")
    private Instant atualizadoEm;
}
